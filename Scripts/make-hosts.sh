#!/usr/bin/env bash
# Writes the Ansible inventory (ansible/inventory/hosts.yml, ignored by Git)
# from the outputs of the bootstrap stack, so no address or account number is
# committed.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/ansible/inventory/hosts.yml"

outputs=$(terraform -chdir="$ROOT/bootstrap" output -json)
out() { jq -r ".$1.value" <<<"$outputs"; }

gitlab_ip=$(out gitlab_public_ip)
runner_ip=$(out runner_public_ip)

if [[ -z "$gitlab_ip" || "$gitlab_ip" == null || -z "$runner_ip" || "$runner_ip" == null ]]; then
  echo "No address in the bootstrap outputs: run terraform apply in bootstrap/ first." >&2
  exit 1
fi

cat >"$OUT" <<EOF
# Generated by Scripts/make-hosts.sh from the bootstrap outputs. Do not edit.
all:
  vars:
    aws_region: eu-west-3
    oidc_issuer_url: $(out oidc_issuer_url)
    oidc_bucket: $(out oidc_bucket)
    tf_state_bucket: $(out state_bucket)
    ecr_registry: $(out registry)
    eks_api_allowed_cidrs: $(jq -c '.eks_api_allowed_cidrs.value' <<<"$outputs")
    admin_principal_arn: $(out admin_principal_arn)
    ci_role_arns:
$(jq -r '.ci_role_arns.value | to_entries[] | "      \(.key): \(.value)"' <<<"$outputs")
  children:
    controller:
      hosts:
        localhost:
          ansible_connection: local
          ansible_python_interpreter: "{{ ansible_playbook_python }}"
    gitlab:
      hosts:
        gitlab-server:
          ansible_host: $gitlab_ip
    runners:
      hosts:
        gitlab-runner:
          ansible_host: $runner_ip
EOF

echo "Wrote $OUT (GitLab $gitlab_ip, runner $runner_ip)"
